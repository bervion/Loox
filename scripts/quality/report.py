#!/usr/bin/env python3
"""Generate the coverage report from source ledgers; never edit outputs by hand."""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

from qualitylib import coverage_summary, load_json_document, source_digest


def repository_root() -> Path:
    return Path(__file__).resolve().parents[2]


def render(root: Path) -> tuple[dict, str]:
    summary = coverage_summary(root)
    payload = {
        "schema_version": 1,
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "generated_by": "scripts/quality/report.py",
        "source_digest": source_digest(root),
        "summary": summary,
        "interpretation": "known records are imported inventory and are not verified coverage"
    }
    lines = [
        "# Generated quality coverage report",
        "",
        "> Generated by `scripts/quality/report.py`. Do not edit this file by hand.",
        "",
        f"Source digest: `{payload['source_digest']}`",
        "",
        "| Contract | Total | Verified | Coverage | Known | Stale | Blocked |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name in ("surfaces", "states", "transitions", "journeys", "critical"):
        row = summary[name]
        statuses = row["by_status"]
        lines.append(
            f"| {name.title()} | {row['total']} | {row['verified']} | {row['verification_percent']:.1f}% | "
            f"{statuses['known']} | {statuses['stale']} | {statuses['blocked']} |"
        )
    lines.extend([
        "",
        "All seeded records are intentionally `known`. This report must not be used to claim verified product coverage until independent evidence promotes records to `verified`.",
        "",
    ])
    return payload, "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=repository_root())
    parser.add_argument("--check", action="store_true", help="check source digest without rewriting outputs")
    args = parser.parse_args()
    project = load_json_document(args.root / "quality/project.yaml")
    json_path = args.root / project["reports"]["json"]
    markdown_path = args.root / project["reports"]["markdown"]
    payload, markdown = render(args.root)
    if args.check:
        if not json_path.exists():
            print(f"missing generated report: {json_path.relative_to(args.root)}")
            return 1
        current = load_json_document(json_path)
        if current.get("source_digest") != payload["source_digest"]:
            print("generated coverage report is stale")
            return 1
        print("generated coverage report is current")
        return 0
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    markdown_path.write_text(markdown, encoding="utf-8")
    print(f"generated {json_path.relative_to(args.root)} and {markdown_path.relative_to(args.root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
